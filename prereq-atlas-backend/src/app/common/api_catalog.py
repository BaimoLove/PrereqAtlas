@dataclass(frozen=True, slots=True)
class Endpoint:
    method: Literal["GET", "POST"]
    path: str
    auth: AuthLevel
    task: str
    mutating: bool
    request: str
    success: str
    errors: tuple[ErrorCode, ...]

    @property
    def full_path(self) -> str:
        """健康入口不带前缀，其余接口统一挂在 /api/v1 下。"""
        if self.path.startswith("/health"):
            return self.path
        return f"{API_V1_PREFIX}{self.path}"


